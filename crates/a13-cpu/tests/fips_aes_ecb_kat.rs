#[test]
fn fips50_keyexp_matches_golden() {
    let mut cpu = make_cpu();
    run_keyexp(&mut cpu);
    let mut ctx = [0u8; 0x100];
    cpu.mem().read_bytes(CTX_VA, &mut ctx);
    assert_eq!(&ctx[0x00..0xb0], &GOLDEN_RK[..], "keyexp diverged from the FIPS-197 golden schedule");
    assert_eq!(&ctx[0x00..0x10], &KEY[..], "rk0 must be the key itself");
    assert_eq!(u32::from_le_bytes(ctx[0xf0..0xf4].try_into().unwrap()), 0xa0, "ctx[0xf0] = rounds*16");
}

#[test]
fn fips50_ecb_encrypt_kat() {
    let mut cpu = make_cpu();
    run_keyexp(&mut cpu);
    // golden schedule check inline (independent of the other test)
    let mut ctx = [0u8; 0x100];
    cpu.mem().read_bytes(CTX_VA, &mut ctx);
    assert_eq!(&ctx[0x00..0xb0], &GOLDEN_RK[..], "precondition: schedule golden");
    run_ecb(&mut cpu, 1);
    let mut out = [0u8; 16];
    cpu.mem().read_bytes(OUT_VA, &mut out);
    assert_eq!(&out[..], &CT[..], "ECB-encrypt through the kernel's own vng core diverged");
}


