//! REAL-DATA repro (BUG #50): the 18C66 fipspost AES-ECB KAT through the
//! kernel's OWN code — the ccaes keyexp (0xfffffff0082a87d0..+0x1F0, the
//! bit-parallel one-round-key-per-iteration expansion with the real Sbox
//! @0x703c65c / Rcon @0x703c650 rodata) and the vng ECB crypt
//! (0xfffffff0082cae30..+0x49C, AESE/AESMC with post-index LDR/STR q and
//! register-offset round-key loads).
//!
//! KAT (extracted from rodata, python-verified): key e680747f… @0x703c08a
//! (the csel-eq normal-boot key), pt 7fea96f9… @0x73c2ed0, expected ct
//! 3d30e636… @0x73c2ee1. fipspost_post_aes_ecb failed memcmp with −75
//! (POST test 4 → fipspost_post returns −4075) at the M5-R frontier.
//!
//! Everything runs at its REAL VA inside one 4 MiB window
//! [0xfffffff007000000, 0xfffffff00B000000) so the kernel's own ADRP
//! fixups resolve unchanged.

use a13_cpu::interp::Interpreter;
use a13_cpu::{CpuBackend, MemAccess, StopReason};

const BASE: u64 = 0xffff_fff0_0700_0000;
/// covers the rodata (Sbox @0x703c65c) through the ECB text end
/// (0x82cb2cc) plus the ctx/out/hlt scratch — ~20 MiB, one window.
const WIN: usize = 24 << 20;

const KEYEXP_VA: u64 = 0xffff_fff0_082a_87d0;
const ECB_VA: u64 = 0xffff_fff0_082c_ae30;
const SBOX_VA: u64 = 0xffff_fff0_0703_c65c;
const RCON_VA: u64 = 0xffff_fff0_0703_c650;
const KEY_VA: u64 = 0xffff_fff0_0703_c08a;
const PT_VA: u64 = 0xffff_fff0_073c_2ed0;
const CTX_VA: u64 = 0xffff_fff0_0840_0000;
const OUT_VA: u64 = 0xffff_fff0_0841_0000;
const HLT_VA: u64 = 0xffff_fff0_0850_0000;

fn idx(va: u64) -> usize { (va - BASE) as usize }

struct Ram(Vec<u8>);
impl Ram {
    fn new() -> Self { Ram(vec![0u8; WIN]) }
    fn put(&mut self, va: u64, bytes: &[u8]) {
        let i = idx(va);
        self.0[i..i + bytes.len()].copy_from_slice(bytes);
    }
    fn get(&self, va: u64, n: usize) -> &[u8] { &self.0[idx(va)..idx(va) + n] }
}
impl MemAccess for Ram {
    fn load(&mut self, addr: u64, size: u8) -> u64 {
        let mut v = [0u8; 8];
        for k in 0..size as usize {
            v[k] = self.0.get(idx(addr) + k).copied().unwrap_or(0);
        }
        u64::from_le_bytes(v)
    }
    fn store(&mut self, addr: u64, size: u8, val: u64) {
        let b = val.to_le_bytes();
        for k in 0..size as usize {
            if let Some(slot) = self.0.get_mut(idx(addr) + k) {
                *slot = b[k];
            }
        }
    }
    fn fetch32(&mut self, addr: u64) -> u32 {
        let i = idx(addr);
        u32::from_le_bytes(self.0[i..i + 4].try_into().unwrap())
    }
}

/// Build the staged machine (code + rodata + KAT vectors at real VAs).
fn make_cpu() -> Interpreter {
    let mut m = Ram::new();
    let keyexp: Vec<u8> = KEYEXP.iter().flat_map(|w| w.to_le_bytes()).collect();
    let ecb: Vec<u8> = ECB.iter().flat_map(|w| w.to_le_bytes()).collect();
    m.put(KEYEXP_VA, &keyexp);
    m.put(ECB_VA, &ecb);
    m.put(SBOX_VA, &SBOX);
    m.put(RCON_VA, &RCON);
    m.put(KEY_VA, &KEY);
    m.put(PT_VA, &PT);
    m.put(HLT_VA, &0xd440_0000u32.to_le_bytes()); // HLT landing for retab
    Interpreter::new(Box::new(m))
}

/// Run the kernel's own keyexp: (x0=key, x1=ctx, w2=4 words, w3=10 rounds).
fn run_keyexp(cpu: &mut Interpreter) {
    cpu.set_reset_vector(KEYEXP_VA);
    cpu.x[0] = KEY_VA;
    cpu.x[1] = CTX_VA;
    cpu.x[2] = 4;
    cpu.x[3] = 10;
    cpu.x[30] = HLT_VA;
    let res = cpu.run(a13_cpu::InterpBudget { max_insn: 5000, max_ns: 60_000_000_000 });
    assert_eq!(res.stop, StopReason::Halted, "keyexp stop={res:?}");
}

/// Run the kernel's own vng ECB: (x0=ctx, w1=nblocks, x2=in, x3=out).
fn run_ecb(cpu: &mut Interpreter, nblocks: u64) {
    cpu.set_reset_vector(ECB_VA);
    cpu.x[0] = CTX_VA;
    cpu.x[1] = nblocks;
    cpu.x[2] = PT_VA;
    cpu.x[3] = OUT_VA;
    cpu.x[30] = HLT_VA;
    let res = cpu.run(a13_cpu::InterpBudget { max_insn: 5000, max_ns: 60_000_000_000 });
    assert_eq!(res.stop, StopReason::Halted, "ecb stop={res:?}");
}

