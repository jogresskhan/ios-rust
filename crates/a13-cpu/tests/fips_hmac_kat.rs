const PAGE: u64 = 0x2000;   // code page (entry at PAGE + 0x730)
const ENTRY: u64 = PAGE + 0x730;
const STATE: u64 = 0x1000;  // 5×u32
const DATA: u64 = 0x11000;
const STACK: u64 = 0x18000;
const HALT: u64 = 0x19000;

/// Run the kernel's compress on `blocks` blocks of `stream`, return the
/// resulting 5-word state.
fn run_compress(stream: &[u8], blocks: usize) -> [u32; 5] {
    let mut ram = vec![0u8; 0x20000];
    let kfn = (PAGE + 0x6f0) as usize; // K table at page+0x6f0 (ADRP+ADD target), fn at page+0x730
    ram[kfn..kfn + COMPRESS.len() * 4].copy_from_slice(
        &COMPRESS.iter().flat_map(|w| w.to_le_bytes()).collect::<Vec<_>>(),
    );
    let d = DATA as usize;
    ram[d..d + blocks * 64].copy_from_slice(&stream[..blocks * 64]);
    let s = STATE as usize;
    ram[s..s + 20].copy_from_slice(&IV);
    ram[HALT as usize..HALT as usize + 4].copy_from_slice(&0xD440_0000u32.to_le_bytes());
    let mut cpu = Interpreter::new(Box::new(Ram(ram)));
    cpu.x[0] = STATE;
    cpu.x[1] = blocks as u64;
    cpu.x[2] = DATA;
    cpu.sp = STACK;
    cpu.x[30] = HALT;
    cpu.set_reset_vector(ENTRY);
    let res = cpu.run(a13_cpu::InterpBudget {
        max_insn: 100_000,
        max_ns: 60_000_000_000,
    });
    assert_eq!(res.stop, StopReason::Halted, "compress must return, stop={res:?}");
    let mut st_bytes = [0u8; 20];
    cpu.mem().read_bytes(STATE, &mut st_bytes);
    let mut st = [0u32; 5];
    for i in 0..5 {
        st[i] = u32::from_le_bytes(st_bytes[i * 4..i * 4 + 4].try_into().unwrap());
    }
    let _ = s;
    st
}

