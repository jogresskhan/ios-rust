//! REAL-DATA repro: the 18C66 fipspost HMAC-SHA1 KAT through the kernel's
//! OWN SHA-1 vng compress bytes (extracted verbatim from the decoded
//! kernelcache at 0xfffffff0082c16f0..0x82c1b64 — K table + function).
//!
//! Calling convention (RE'd from the bytes): x0 = 5×u32 state, x1 = nblocks,
//! x2 = data. The ADRP at entry resolves to the code's own page, so the
//! K table must sit at page_base+0x6f0 (exactly the kernel's layout).
//!
//! Reference states computed by the sha1 reference in the generator script
//! (tools/re/oracle/kat_ref.py lineage) — inner = ipad||msg||pad (4 blocks),
//! outer = opad||inner||pad (2 blocks).

use a13_cpu::interp::Interpreter;
use a13_cpu::{CpuBackend, MemAccess, StopReason};

struct Ram(Vec<u8>);
impl MemAccess for Ram {
    fn load(&mut self, addr: u64, size: u8) -> u64 {
        let mut v = [0u8; 8];
        for k in 0..size as usize {
            v[k] = self.0.get((addr + k as u64) as usize).copied().unwrap_or(0);
        }
        u64::from_le_bytes(v)
    }
    fn store(&mut self, addr: u64, size: u8, val: u64) {
        let b = val.to_le_bytes();
        for k in 0..size as usize {
            if let Some(slot) = self.0.get_mut((addr + k as u64) as usize) {
                *slot = b[k];
            }
        }
    }
    fn fetch32(&mut self, addr: u64) -> u32 {
        u32::from_le_bytes(
            self.0[(addr as usize)..(addr as usize) + 4]
                .try_into()
                .unwrap(),
        )
    }
}

