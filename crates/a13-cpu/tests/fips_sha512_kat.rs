const PAGE: u64 = 0x10000;    // function base (page-aligned; adrp patched)
const ENTRY: u64 = PAGE;
const KPAGE: u64 = 0x40000;   // K table page; table at KPAGE + 0x640
const STATE: u64 = 0x8000;
const DATA: u64 = 0x50000;
const STACK: u64 = 0x60000;
const HALT: u64 = 0x70000;

fn run_compress(stream: &[u8], blocks: usize) -> [u64; 8] {
    let mut ram = vec![0u8; 0x80000];
    let f = PAGE as usize;
    ram[f..f + COMPRESS.len() * 4].copy_from_slice(
        &COMPRESS.iter().flat_map(|w| w.to_le_bytes()).collect::<Vec<_>>(),
    );
    let k = (KPAGE + 0x640) as usize;
    ram[k..k + KTABLE.len()].copy_from_slice(&KTABLE);
    let d = DATA as usize;
    ram[d..d + blocks * 128].copy_from_slice(&stream[..blocks * 128]);
    let s = STATE as usize;
    ram[s..s + 64].copy_from_slice(&IV);
    ram[HALT as usize..HALT as usize + 4].copy_from_slice(&0xD440_0000u32.to_le_bytes());
    let mut cpu = Interpreter::new(Box::new(Ram(ram)));
    cpu.x[0] = STATE;
    cpu.x[1] = blocks as u64;
    cpu.x[2] = DATA;
    cpu.sp = STACK;
    cpu.x[30] = HALT;
    cpu.set_reset_vector(ENTRY);
    let res = cpu.run(a13_cpu::InterpBudget {
        max_insn: 2_000_000,
        max_ns: 60_000_000_000,
    });
    assert_eq!(res.stop, StopReason::Halted, "compress must return, stop={res:?}");
    let mut buf = [0u8; 64];
    cpu.mem().read_bytes(STATE, &mut buf);
    let mut st = [0u64; 8];
    for i in 0..8 {
        st[i] = u64::from_le_bytes(buf[i * 8..i * 8 + 8].try_into().unwrap());
    }
    st
}

