/// Look up a BSD syscall name by number (binary search; the table is sorted).
pub fn name(num: u32) -> Option<&'static str> {
    BSD_SYSCALLS
        .binary_search_by_key(&num, |e| e.0)
        .ok()
        .map(|i| BSD_SYSCALLS[i].1)
}

