//! syscalls — BSD syscall number table and 64-bit wire structs.
//!
//! Guests enter the BSD side of the Darwin syscall ABI with `svc #0` and the
//! (non-negative) syscall number in x16. The table below is the canonical
//! `syscalls.master` numbering as shipped by the Darwin 20.6.0 kernel line
//! (xnu-7195.141.2); entries guarded by kernel options the iOS kernel enables
//! (SOCKETS, PSYNCH, SYSV_*, CONFIG_WORKQUEUE, CONFIG_MACF, CONFIG_EMBEDDED,
//! CONFIG_MEMORYSTATUS, NECP, CONFIG_CODE_DECRYPTION, CONFIG_COALITIONS, PGO,
//! CONFIG_PERSONAS, CONFIG_CSR, CONFIG_EXT_RESOLVER, CONFIG_PROC_UUID_POLICY)
//! use their enabled name; `nosys`/`enosys` placeholder slots are omitted.
//! The vendored master ends at 545 (`proc_info_extended_id`); the platform
//! syscall (0x80000000) is not part of this table, see `abi`.
//!
//! Note on 520/521: `syscalls.master` (the generator of record) assigns
//! 520 = `terminate_with_payload` and 521 = `abort_with_payload`. The
//! distilled `darwin-abi.h` header lists them swapped; this table follows
//! `syscalls.master`.
//!
//! Source: darling-xnu (Darwin 20.6.0 lineage) bsd/kern/syscalls.master
//! Source: xnu-7195.141.2 bsd/kern/syscalls.master
//! Source: arlinux-xnu src/darwin-abi.h (darwin_syscall enum, struct layouts)

